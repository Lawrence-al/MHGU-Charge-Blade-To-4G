// 构建时嵌入当前 asset；0x00～0x4E 使用 asset，0x4F 恢复原版，保留 SAED 新增的 0x50。
pub use cb_game::resource::{
    HDP_HEADER_SIZE as HEADER_SIZE, HDP_ORIGINAL_COUNT as ORIGINAL_COUNT,
    HDP_RECORD_SIZE as RECORD_SIZE,
};
pub const ASSET_SIZE: usize = HEADER_SIZE + ORIGINAL_COUNT * RECORD_SIZE;

pub const ASSET: &[u8; ASSET_SIZE] = include_bytes!(
    "../../../assets/romfs/nativeNX/arc/player/quest/w14.arc/hit/pl_we14_hitdata.4E2EF008"
);

// GU dump 原版 0x4F 的完整快照：记录开头 106、持续 6、动作值 55。
// 即使加载的是修改后的 HDP，也写回此快照；新增 0x50 继续使用 SAED 自己的数据。
const ORIGINAL_4F: [u8; RECORD_SIZE] = [
    0x6A, 0x00, 0x06, 0x00, 0x37, 0x00, 0x00, 0x00, 0x01, 0x00, 0x32, 0x00, 0x02, 0x00, 0x00, 0x00,
    0x02, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x02, 0x00, 0x00, 0x02, 0x04, 0x05, 0x00, 0x00, 0x00, 0x00, 0x80, 0x3F, 0x00, 0x00, 0x80, 0x3F,
    0x37, 0x00, 0x00, 0x00, 0x00, 0x00, 0x23, 0x00,
];

pub fn apply_original(data: &mut [u8]) {
    let offset = HEADER_SIZE + 0x4F * RECORD_SIZE;
    data[HEADER_SIZE..offset].copy_from_slice(&ASSET[HEADER_SIZE..offset]);
    data[offset..ASSET_SIZE].copy_from_slice(&ORIGINAL_4F);
}

// HDP 加载后扩容为 81 条；保留其它 asset 的动作值改动，不改文件。
pub const EXTENDED_SIZE: usize = HEADER_SIZE + (ORIGINAL_COUNT + 1) * RECORD_SIZE;

// 当前 asset 的 0x4F 完整快照：持续 8、动作值 100，作为新增 0x50。
const NEW_50: [u8; RECORD_SIZE] = [
    0x00, 0x00, 0x08, 0x00, 0x64, 0x00, 0x00, 0x00, 0x01, 0x00, 0x32, 0x00, 0x02, 0x00, 0x00, 0x00,
    0x02, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x02, 0x00, 0x00, 0x02, 0x04, 0x05, 0x00, 0x00, 0x00, 0x00, 0x80, 0x3F, 0x00, 0x00, 0x80, 0x3F,
    0x37, 0x00, 0x00, 0x00, 0x00, 0x00, 0x23, 0x00,
];

pub fn extend(original: &[u8], extended: &mut [u8]) {
    let old_size = HEADER_SIZE + ORIGINAL_COUNT * RECORD_SIZE;
    extended[..old_size].copy_from_slice(&original[..old_size]);
    extended[8..12].copy_from_slice(&((ORIGINAL_COUNT + 1) as u32).to_le_bytes());
    extended[old_size..EXTENDED_SIZE].copy_from_slice(&NEW_50);
}

/// 独立覆盖新增 0x50；原版 0x4F 不作为第三下的数据来源。
pub fn apply_extra(data: &mut [u8]) {
    let offset = HEADER_SIZE + ORIGINAL_COUNT * RECORD_SIZE;
    data[offset..EXTENDED_SIZE].copy_from_slice(&NEW_50);
}
